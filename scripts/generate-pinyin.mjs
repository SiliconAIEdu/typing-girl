// Authoring step: build src/pinyin-data.js so Chinese lessons can show pinyin above each character.
// Requires: npm install --prefix scripts/assets
import fs from 'node:fs';
import { pinyin } from './assets/node_modules/pinyin-pro/dist/index.mjs';
const chinese = JSON.parse(
  fs.readFileSync(new URL('../src/chinese-curriculum.json', import.meta.url), 'utf8'),
);
const texts = new Set();
for (const u of chinese) {
  for (const t of [...u.words, ...u.sentences]) texts.add(t);
  for (const story of u.stories) for (const t of story.text) texts.add(t);
}
const map = {};
for (const text of texts) {
  const chars = [...text];
  const result = pinyin(text, { type: 'all', toneType: 'symbol' });
  if (result.length !== chars.length) throw Error('Length mismatch: ' + text);
  map[text] = result.map(r => (r.isZh ? r.pinyin : '')).join(' ');
}
fs.writeFileSync(
  new URL('../src/pinyin-data.js', import.meta.url),
  '// Generated by scripts/generate-pinyin.mjs from src/chinese-curriculum.json.\n// Each value lists one syllable per character, separated by spaces; non-Chinese characters are empty.\nexport const PINYIN=' +
    JSON.stringify(map) +
    ';\n',
);
console.log(`Pinyin ready: ${texts.size} Chinese texts.`);
